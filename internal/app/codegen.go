package app

import (
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"

	schemaapi "organon/internal/schema/api"
)

// GenerateTS returns a TypeScript module with types, constants, view
// schemas, and a typed client for the app (spec 13.1 organon codegen ts).
// Types come from the owner audience's views: fields hidden from the
// public view are optional, and private fields do not exist on the client.
func GenerateTS(c *Compiled, clientImport string) string {
	if clientImport == "" {
		clientImport = "@organon/client"
	}
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("// Generated by `organon codegen ts` from manifest %s (%s). Do not edit.\n", c.Manifest.App.App, short12(c.Manifest.Hash))
	w("import { OrganonClient, TypeApi, type ClientOptions, type Feature, type FeatureId, type Decimal, type Timestamp, type BlobRef } from %q;\n\n", clientImport)
	w("export type { Feature, FeatureId, Decimal, Timestamp, BlobRef };\n\n")
	var types []*schemaapi.CompiledType
	for _, ct := range c.Types.All() {
		if !ct.ID.IsSystem() || ct.Base() == schemaapi.TypeUser || ct.Base() == schemaapi.TypeTeam || ct.Base() == schemaapi.TypeGrant {
			types = append(types, ct)
		}
	}
	schemas := map[string]any{}
	for _, ct := range types {
		name := pascal(ct.Name)
		read := viewSchema(ct, schemaapi.AudOwner, schemaapi.DirRead)
		public := ct.View(schemaapi.AudPublic, schemaapi.DirRead).Readable
		w("/** %s (%s) */\n", orStr(ct.Title, name), ct.ID)
		w("export interface %sData {\n", name)
		writeProps(&b, read, func(k string) bool { return public["/"+k] && contains(read["required"], k) })
		w("}\n")
		create := viewSchema(ct, schemaapi.AudOwner, schemaapi.DirCreate)
		w("export interface %sCreate {\n", name)
		writeProps(&b, create, func(k string) bool { return contains(create["required"], k) })
		w("}\n")
		update := viewSchema(ct, schemaapi.AudOwner, schemaapi.DirUpdate)
		w("export interface %sUpdate {\n", name)
		writeProps(&b, update, func(string) bool { return false })
		w("}\n")
		w("export type %s = Feature<%q, %sData>;\n", name, ct.Name, name)
		for _, f := range ct.TopFields() {
			if f.Kind.String() == "enum" && public[f.Path] {
				vals, _ := json.Marshal(f.Type.Enum)
				w("export const %s%s = %s as const;\n", name, pascal(f.Path[1:]), vals)
			}
		}
		for path, sm := range ct.StateMachines {
			tr, _ := json.Marshal(sm.Transitions)
			var list []map[string]string
			_ = json.Unmarshal(tr, &list)
			clean := make([]map[string]string, len(list))
			for i, t := range list {
				clean[i] = map[string]string{"from": t["From"], "to": t["To"], "action": t["Action"]}
			}
			out, _ := json.Marshal(clean)
			w("export const %s%sTransitions = %s as const;\n", name, pascal(path[1:]), out)
		}
		w("\n")
		schemas[ct.Name] = map[string]any{"create": create, "update": update}
	}
	// Action input and output types (spec 10.3: a typed method per action).
	actions := map[string][]string{}
	for _, ct := range types {
		name := pascal(ct.Name)
		seen := map[string]bool{}
		add := func(action, in, out string) {
			if seen[action] {
				return
			}
			seen[action] = true
			actions[ct.Name] = append(actions[ct.Name], fmt.Sprintf("    %s: (f: { id: string }, input?: %s) => c.action<%s>(%q, f.id, %q, input),\n",
				ident(action), in, out, ct.Name, action))
		}
		for _, f := range c.Flows.All() {
			if f.Def.Trigger.Action == "" || !f.Matches(ct) {
				continue
			}
			in, out := "Record<string, unknown>", "unknown"
			if len(f.Def.Input) > 0 {
				in = name + pascal(f.Def.Trigger.Action) + "Input"
				var m map[string]any
				_ = json.Unmarshal(f.Def.Input, &m)
				w("export type %s = %s;\n", in, tsType(m))
			}
			if len(f.Def.Output) > 0 {
				out = name + pascal(f.Def.Trigger.Action) + "Output"
				var m map[string]any
				_ = json.Unmarshal(f.Def.Output, &m)
				w("export type %s = %s;\n", out, tsType(m))
			}
			add(f.Def.Trigger.Action, in, out)
		}
		for _, sm := range ct.StateMachines {
			for _, t := range sm.Transitions {
				add(t.Action, "Record<string, unknown>", "unknown")
			}
			add("transition", "{ action?: string; to?: string }", "unknown")
		}
		if ct.HasTrait(schemaapi.TraitOwnable) {
			add("transfer", "{ to: string }", "unknown")
		}
	}
	sj, _ := json.MarshalIndent(schemas, "", "  ")
	w("\n/** Create and update views, for local form validation (spec 13.1). */\nexport const schemas = %s as const;\n\n", sj)
	w("export function createClient(opts: ClientOptions = {}) {\n  const c = new OrganonClient(opts);\n  return {\n    raw: c,\n    auth: c.auth,\n")
	for _, ct := range types {
		name := pascal(ct.Name)
		w("    %s: Object.assign(new TypeApi<%q, %sData, %sCreate, %sUpdate>(c, %q), {\n      actions: {\n%s      },\n    }),\n",
			ident(ct.Name), ct.Name, name, name, name, ct.Name, strings.Join(actions[ct.Name], ""))
	}
	w("  };\n}\n\nexport type Client = ReturnType<typeof createClient>;\n")
	return b.String()
}

func short12(h string) string {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}

func orStr(a, b string) string {
	if a != "" {
		return a
	}
	return b
}

func viewSchema(ct *schemaapi.CompiledType, a schemaapi.Audience, d schemaapi.Direction) map[string]any {
	var m map[string]any
	_ = json.Unmarshal(ct.View(a, d).JSONSchema, &m)
	delete(m, "$schema")
	delete(m, "$id")
	return m
}

func contains(list any, k string) bool {
	l, _ := list.([]any)
	for _, x := range l {
		if x == k {
			return true
		}
	}
	return false
}

func writeProps(b *strings.Builder, schema map[string]any, required func(string) bool) {
	props, _ := schema["properties"].(map[string]any)
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		p, _ := props[k].(map[string]any)
		opt := "?"
		if required(k) {
			opt = ""
		}
		ro := ""
		if p["readOnly"] == true {
			ro = "readonly "
		}
		if d, ok := p["description"].(string); ok {
			fmt.Fprintf(b, "  /** %s */\n", strings.ReplaceAll(d, "*/", "*\\/"))
		}
		fmt.Fprintf(b, "  %s%s%s: %s;\n", ro, propName(k), opt, tsType(p))
	}
}

var identRe = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func propName(k string) string {
	if identRe.MatchString(k) {
		return k
	}
	return fmt.Sprintf("%q", k)
}

func ident(k string) string {
	if identRe.MatchString(k) {
		return k
	}
	return fmt.Sprintf("%q", k)
}

func pascal(s string) string {
	parts := regexp.MustCompile(`[^A-Za-z0-9]+`).Split(s, -1)
	var b strings.Builder
	for _, p := range parts {
		if p != "" {
			b.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	return b.String()
}

// tsType maps a view JSON Schema to a TypeScript type.
func tsType(s map[string]any) string {
	if s == nil {
		return "unknown"
	}
	if e, ok := s["enum"].([]any); ok {
		parts := make([]string, len(e))
		for i, v := range e {
			if v == nil {
				parts[i] = "null"
			} else {
				b, _ := json.Marshal(v)
				parts[i] = string(b)
			}
		}
		return strings.Join(parts, " | ")
	}
	if one, ok := s["oneOf"].([]any); ok {
		parts := make([]string, len(one))
		for i, br := range one {
			m, _ := br.(map[string]any)
			parts[i] = tsType(m)
		}
		return strings.Join(parts, " | ")
	}
	t, nullable := "", false
	switch x := s["type"].(type) {
	case string:
		t = x
	case []any:
		if len(x) > 0 {
			t, _ = x[0].(string)
			nullable = len(x) > 1
		}
	}
	var out string
	switch t {
	case "string":
		switch {
		case s["format"] == "uuid":
			out = "FeatureId"
		case s["format"] == "date-time":
			out = "Timestamp"
		case s["pattern"] == `^-?[0-9]+(\.[0-9]+)?$`:
			out = "Decimal"
		default:
			out = "string"
		}
	case "integer", "number":
		out = "number"
	case "boolean":
		out = "boolean"
	case "array":
		items, _ := s["items"].(map[string]any)
		it := tsType(items)
		if strings.Contains(it, " ") {
			it = "(" + it + ")"
		}
		out = it + "[]"
	case "object":
		props, _ := s["properties"].(map[string]any)
		if isBlob(props) {
			out = "BlobRef"
			break
		}
		if len(props) == 0 {
			out = "Record<string, unknown>"
			break
		}
		var b strings.Builder
		b.WriteString("{ ")
		keys := make([]string, 0, len(props))
		for k := range props {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			p, _ := props[k].(map[string]any)
			opt := "?"
			if contains(s["required"], k) {
				opt = ""
			}
			fmt.Fprintf(&b, "%s%s: %s; ", propName(k), opt, tsType(p))
		}
		b.WriteString("}")
		out = b.String()
	default:
		out = "unknown"
	}
	if nullable {
		out += " | null"
	}
	return out
}

// isBlob recognizes the view schema of Blob fields {id, size, contentType}.
func isBlob(props map[string]any) bool {
	if len(props) != 3 {
		return false
	}
	for _, k := range []string{"id", "size", "contentType"} {
		if _, ok := props[k]; !ok {
			return false
		}
	}
	return true
}
