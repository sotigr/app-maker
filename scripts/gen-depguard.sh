#!/usr/bin/env bash
# Generates .golangci.yml with depguard rules encoding the layer rules of
# spec section 15.2 as amended by docs/adr/0004-layer-import-rules.md.
set -euo pipefail

MOD=app-maker
CONTEXTS=(schema content access query change flow runtime integration manifest)
PURE_LIBS=(
  github.com/expr-lang/expr
  github.com/santhosh-tekuri/jsonschema/v6
  github.com/cockroachdb/apd/v3
  github.com/google/uuid
)

out="$(dirname "$0")/../.golangci.yml"

all_apis() {
  for c in "${CONTEXTS[@]}"; do echo "            - ${MOD}/internal/${c}/api"; done
}

others_internals() { # $1 = own context
  for c in "${CONTEXTS[@]}"; do
    [[ "$c" == "$1" ]] && continue
    for l in domain application infrastructure interfaces repotest; do
      echo "            - pkg: ${MOD}/internal/${c}/${l}"
      echo "              desc: contexts talk only through api packages (spec 15.4)"
    done
  done
}

{
cat <<EOF
# Generated by scripts/gen-depguard.sh - do not edit by hand.
version: "2"
linters:
  default: standard
  enable:
    - depguard
  settings:
    depguard:
      rules:
        kernel:
          list-mode: strict
          files: ["**/internal/kernel/**", "!\$test"]
          allow:
            - \$gostd
            - ${MOD}/internal/kernel
            - github.com/google/uuid
            - github.com/cockroachdb/apd/v3
        platform:
          list-mode: lax
          files: ["**/platform/**", "!\$test"]
          deny:
$(for c in "${CONTEXTS[@]}"; do echo "            - pkg: ${MOD}/internal/${c}"; echo "              desc: platform holds no domain logic; it may use only the kernel (spec 15.1)"; done)
EOF

for c in "${CONTEXTS[@]}"; do
cat <<EOF
        ${c}-api:
          list-mode: strict
          files: ["**/internal/${c}/api/**", "!\$test"]
          allow:
            - \$gostd
            - ${MOD}/internal/kernel
$(all_apis)
        ${c}-domain:
          list-mode: strict
          files: ["**/internal/${c}/domain/**", "!\$test"]
          allow:
            - \$gostd
            - ${MOD}/internal/kernel
            - ${MOD}/internal/${c}/domain
$(all_apis)
$(for l in "${PURE_LIBS[@]}"; do echo "            - ${l}"; done)
        ${c}-application:
          list-mode: strict
          files: ["**/internal/${c}/application/**", "!\$test"]
          allow:
            - \$gostd
            - ${MOD}/internal/kernel
            - ${MOD}/internal/${c}/domain
            - ${MOD}/internal/${c}/application
$(all_apis)
$(for l in "${PURE_LIBS[@]}"; do echo "            - ${l}"; done)
            - golang.org/x/sync
        ${c}-infrastructure:
          list-mode: lax
          files: ["**/internal/${c}/infrastructure/**", "!\$test"]
          deny:
            - pkg: ${MOD}/internal/${c}/interfaces
              desc: infrastructure must not import interfaces (spec 15.2)
$(others_internals "$c")
        ${c}-interfaces:
          list-mode: lax
          files: ["**/internal/${c}/interfaces/**", "!\$test"]
          deny:
            - pkg: ${MOD}/internal/${c}/infrastructure
              desc: interfaces must not import infrastructure (spec 15.2)
            - pkg: ${MOD}/internal/${c}/domain
              desc: interfaces use application DTOs, not domain internals (spec 15.2)
$(others_internals "$c")
EOF
done

cat <<EOF
formatters:
  enable:
    - gofmt
    - goimports
EOF
} > "$out"

echo "wrote $out"
